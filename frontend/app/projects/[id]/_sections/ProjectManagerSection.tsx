const CHART_WIDTH = 640;
const CHART_HEIGHT = 240;
const CHART_PAD_X = 42;
const CHART_PAD_Y = 26;


function isChartNumber(
  value: number | null,
): value is number {
  return (
    value !== null
    &&
    Number.isFinite(
      value,
    )
  );
}


function chartMaximum(
  series:
    Array<
      Array<
        number | null
      >
    >,
) {
  const values =
    series
      .flat()
      .filter(
        isChartNumber,
      );


  return Math.max(
    1,
    ...values,
  );
}


function chartX(
  index: number,
  count: number,
) {
  const drawableWidth =
    CHART_WIDTH
    -
    (
      CHART_PAD_X
      *
      2
    );


  if (
    count
    <=
    1
  ) {
    return (
      CHART_PAD_X
      +
      drawableWidth / 2
    );
  }


  return (
    CHART_PAD_X
    +
    (
      index
      /
      (
        count - 1
      )
    )
    *
    drawableWidth
  );
}


function chartY(
  value: number,
  maximum: number,
) {
  const drawableHeight =
    CHART_HEIGHT
    -
    (
      CHART_PAD_Y
      *
      2
    );


  const safeValue =
    Math.max(
      0,
      value,
    );


  return (
    CHART_HEIGHT
    -
    CHART_PAD_Y
    -
    (
      safeValue
      /
      maximum
    )
    *
    drawableHeight
  );
}


function numericSeriesPoints(
  values: number[],
  maximum: number,
) {
  return values
    .map(
      (
        value,
        index,
      ) =>
        [
          chartX(
            index,
            values.length,
          ).toFixed(
            2,
          ),

          chartY(
            value,
            maximum,
          ).toFixed(
            2,
          ),
        ].join(
          ",",
        ),
    )
    .join(
      " ",
    );
}


function nullableSeriesSegments(
  values:
    Array<
      number | null
    >,
  maximum: number,
) {
  const segments:
    string[] = [];

  let current:
    string[] = [];


  values.forEach(
    (
      value,
      index,
    ) => {
      if (
        !isChartNumber(
          value,
        )
      ) {
        if (
          current.length
          >
          0
        ) {
          segments.push(
            current.join(
              " ",
            ),
          );

          current = [];
        }

        return;
      }


      current.push(
        [
          chartX(
            index,
            values.length,
          ).toFixed(
            2,
          ),

          chartY(
            value,
            maximum,
          ).toFixed(
            2,
          ),
        ].join(
          ",",
        ),
      );
    },
  );


  if (
    current.length
    >
    0
  ) {
    segments.push(
      current.join(
        " ",
      ),
    );
  }


  return segments;
}


function nullableSeriesDots(
  values:
    Array<
      number | null
    >,
  maximum: number,
) {
  return values
    .map(
      (
        value,
        index,
      ) => {
        if (
          !isChartNumber(
            value,
          )
        ) {
          return null;
        }


        return {
          x:
            chartX(
              index,
              values.length,
            ),

          y:
            chartY(
              value,
              maximum,
            ),

          value,
        };
      },
    )
    .filter(
      (
        point,
      ): point is {
        x: number;
        y: number;
        value: number;
      } =>
        point !== null,
    );
}


