function messageFrom(error: unknown, fallback: string) {
  if (typeof error === "object" && error && "response" in error) {
    const detail = (error as { response?: { data?: { detail?: unknown } } }).response?.data?.detail;
    if (typeof detail === "string") return detail;
    if (detail && typeof detail === "object" && "message" in detail) {
      const code = (detail as { code?: unknown }).code;
      if (code === "generation_temporarily_unavailable") {
        return "Le service IA est temporairement indisponible. Réessayez dans quelques instants.";
      }
      if (code === "candidate_authority_rejected") {
        return "Le backlog proposé contient une référence non validée. La génération est bloquée pour protéger la cohérence du projet.";
      }
      const message = (detail as { message?: unknown }).message;
      if (typeof message === "string") return message;
    }
  }
  return fallback;
}

function valueAsNumber(value: string, fallback: number) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}




