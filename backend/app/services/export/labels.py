_BY_LANGUAGE = {"fr": FR, "en": EN}

# Diagram order shared by every builder (same as the frontend).
DIAGRAM_ORDER = ("use_case", "class_diagram", "sequence", "activity")


def labels_for(language: str | None) -> dict[str, str]:
    """Labels for the project's output language (unknown -> French)."""
    return _BY_LANGUAGE[normalize_output_language(language)]


def category_label(labels: dict[str, str], category: str) -> str:
    """Readable source category, falling back to the raw canonical code."""
    return labels.get(f"category_{category}", category)


def status_label(labels: dict[str, str], status: str) -> str:
    """Readable stack layer status (recommended, not_applicable, ...)."""
    return labels.get(f"status_{status}", str(status or ""))


def criteria_label(labels: dict[str, str], criterion: str) -> str:
    """Readable startup-score criterion, raw code if unknown."""
    return labels.get(f"criteria_{criterion}", criterion)


def layer_label(labels: dict[str, str], layer: str) -> str:
    """Readable stack layer name; project-specific layers are prettified."""
    return labels.get(f"layer_{layer}") or str(layer).replace("_", " ").capitalize()
